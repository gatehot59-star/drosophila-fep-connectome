static inline int16_t swarm_tanh_q15(int32_t pre) {
    /* pre: acumulador en Q15. Mapear a [-4,4] con paso SWARM_LUT_STEP. */
    int32_t q = (pre * 255) / (8 * 32768);   /* indice continuo */
    int32_t i = q + 128;
    if (i < 0) return -32767;
    if (i > 255) return 32767;
    return SWARM_TANH_LUT[i];
}

